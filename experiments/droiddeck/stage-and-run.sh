#!/data/data/com.termux/files/usr/bin/bash
set -euo pipefail
export PATH=/data/data/com.termux/files/usr/bin:/system/bin
p=/data/data/com.termux/files/home/mavk-droiddeck-poc-20261015
if test -e "$p"; then echo 'NO_GO fresh experiment path already exists'; exit 20; fi
mkdir -p "$p/root" "$p/hybris"
echo STAGE=verify_component_bytes
test "$(sha256sum /data/local/tmp/mavk-droiddeck-linuxfs-r9.tar.zst | cut -d' ' -f1)" = d3240c1531531615b0dd06b6ad56e92db9015a8641eb18c3a613835ae45992e7
test "$(sha256sum /data/local/tmp/mavk-droiddeck-hybris-4073873.tzst | cut -d' ' -f1)" = 014fa3501723c6dddc50750a58170f74a8b1d1e6d558e44deec37beb72e0bbd7
echo STAGE=extract_minimal_droiddeck_runtime
tar --zstd -xf /data/local/tmp/mavk-droiddeck-linuxfs-r9.tar.zst -C "$p/root" --wildcards \
 './usr/lib/libc.so.6' './usr/lib/libm.so.6' './usr/lib/ld-linux-aarch64.so.1' \
 './usr/lib/libdl.so.2' './usr/lib/libpthread.so.0' './usr/lib/librt.so.1' \
 './usr/lib/libstdc++.so.6*' './usr/lib/libgcc_s.so.1' './usr/lib/libxcb.so*' \
 './usr/lib/libX11.so*' './usr/lib/libX11-xcb.so*' './usr/lib/libXau.so*' \
 './usr/lib/libXdmcp.so*' './usr/lib/libwayland*.so*' './usr/lib/libffi.so*' \
 './usr/lib/libexpat.so*' './usr/lib/libvulkan.so*' './usr/lib/libzstd.so*' \
 './usr/lib/libxshmfence.so*' './opt/android-host/*'
tar --zstd -xf /data/local/tmp/mavk-droiddeck-hybris-4073873.tzst -C "$p/hybris"
cp /data/local/tmp/mavk-hybris-probe "$p/probe"
cp /data/local/tmp/mavk-triangle.vert.spv "$p/triangle.vert.spv"
cp /data/local/tmp/mavk-triangle.frag.spv "$p/triangle.frag.spv"
chmod 700 "$p/probe"
echo STAGE=runtime_footprint
du -sh "$p"
id
echo STAGE=glibc_loader_dependency_check
export HYBRIS_ANDROID_SDK_VERSION=36
export HYBRIS_VULKAN_HAL=/vendor/lib64/hw/vulkan.mali.so
export HYBRIS_LINKER_DIR="$p/hybris/lib/libhybris/linker"
export HYBRIS_LD_LIBRARY_PATH=/system/lib64:/system_ext/lib64:/vendor/lib64/egl:/vendor/lib64/hw:/vendor/lib64
export VK_ICD_FILENAMES="$p/icd.json"
unset VK_INSTANCE_LAYERS VK_LAYER_PATH LD_PRELOAD LD_LIBRARY_PATH || true
# Directly load this glibc ICD through the runtime's Vulkan loader; the manifest
# is generated by the host and is confined to this disposable experiment.
cp /data/local/tmp/mavk-hybris-icd.json "$p/icd.json"
timeout 20 "$p/root/usr/lib/ld-linux-aarch64.so.1" --library-path "$p/root/usr/lib:$p/hybris/lib" \
 "$p/probe" "$p/root/usr/lib/libvulkan.so.1" "$p/triangle.vert.spv" "$p/triangle.frag.spv"
